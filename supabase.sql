-- INISIATOR / Supabase PostgreSQL schema
-- Paste into Supabase SQL Editor and run once on a fresh project.
-- Authentication is managed by Supabase Auth (auth.users); never store passwords here.

create table public.users (
  id uuid primary key references auth.users(id) on delete cascade,
  name varchar(100) not null,
  email varchar(150) unique not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.categories (
  id bigint generated by default as identity primary key,
  user_id uuid references public.users(id) on delete cascade,
  name varchar(50) not null,
  type varchar(10) not null check (type in ('income', 'expense')),
  icon varchar(50),
  color varchar(20),
  created_at timestamptz not null default now()
);

create table public.transactions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(id) on delete cascade,
  category_id bigint not null references public.categories(id) on delete restrict,
  type varchar(10) not null check (type in ('income', 'expense')),
  amount numeric(14,2) not null check (amount > 0),
  transaction_date date not null default current_date,
  description text,
  source varchar(20) not null default 'manual' check (source in ('manual', 'shopping_list', 'split_bill', 'subscription')),
  reference_id varchar(100),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.budgets (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(id) on delete cascade,
  category_id bigint not null references public.categories(id) on delete cascade,
  limit_amount numeric(14,2) not null check (limit_amount > 0),
  month smallint not null check (month between 1 and 12),
  year smallint not null check (year >= 2024),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint uq_user_category_period unique (user_id, category_id, month, year)
);

create table public.shopping_lists (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(id) on delete cascade,
  category_id bigint not null references public.categories(id) on delete restrict,
  title varchar(100) not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.shopping_items (
  id bigint generated by default as identity primary key,
  shopping_list_id bigint not null references public.shopping_lists(id) on delete cascade,
  name varchar(100) not null,
  estimated_price numeric(14,2) not null default 0 check (estimated_price >= 0),
  actual_price numeric(14,2) check (actual_price >= 0),
  is_purchased boolean not null default false,
  purchased_at timestamptz,
  created_at timestamptz not null default now()
);

create table public.split_bills (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.users(id) on delete cascade,
  title varchar(100) not null,
  total_amount numeric(14,2) not null check (total_amount >= 0),
  tax_amount numeric(14,2) not null default 0 check (tax_amount >= 0),
  discount_amount numeric(14,2) not null default 0 check (discount_amount >= 0),
  guest_token uuid not null unique default gen_random_uuid(),
  status varchar(20) not null default 'active' check (status in ('active', 'settled')),
  created_at timestamptz not null default now(),
  settled_at timestamptz
);

create table public.split_bill_members (
  id bigint generated by default as identity primary key,
  split_bill_id uuid not null references public.split_bills(id) on delete cascade,
  name varchar(100) not null,
  phone_number varchar(20),
  amount_owed numeric(14,2) not null default 0 check (amount_owed >= 0),
  is_paid boolean not null default false,
  paid_at timestamptz,
  constraint uq_split_bill_member_name unique (split_bill_id, name)
);

create table public.split_bill_items (
  id bigint generated by default as identity primary key,
  split_bill_id uuid not null references public.split_bills(id) on delete cascade,
  name varchar(100) not null,
  price numeric(14,2) not null check (price >= 0),
  quantity integer not null default 1 check (quantity > 0)
);

create table public.split_bill_item_assignments (
  id bigint generated by default as identity primary key,
  split_bill_item_id bigint not null references public.split_bill_items(id) on delete cascade,
  split_bill_member_id bigint not null references public.split_bill_members(id) on delete cascade,
  split_ratio numeric(5,4) not null default 1 check (split_ratio > 0 and split_ratio <= 1),
  constraint uq_item_member_assignment unique (split_bill_item_id, split_bill_member_id)
);

create table public.subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(id) on delete cascade,
  category_id bigint not null references public.categories(id) on delete restrict,
  service_name varchar(100) not null,
  amount numeric(14,2) not null check (amount > 0),
  billing_cycle varchar(20) not null default 'monthly' check (billing_cycle in ('monthly', 'yearly', 'weekly')),
  due_day smallint not null check (due_day between 1 and 31),
  next_due_date date not null,
  reminder_days_before smallint not null default 3 check (reminder_days_before >= 0),
  is_active boolean not null default true,
  last_paid_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index idx_transactions_user_date on public.transactions(user_id, transaction_date);
create index idx_budgets_user_period on public.budgets(user_id, year, month);
create index idx_split_bills_guest_token on public.split_bills(guest_token);
create index idx_subscriptions_due on public.subscriptions(is_active, next_due_date);

-- Row-level security: users can access only their own records; system categories are readable.
alter table public.users enable row level security;
alter table public.categories enable row level security;
alter table public.transactions enable row level security;
alter table public.budgets enable row level security;
alter table public.shopping_lists enable row level security;
alter table public.shopping_items enable row level security;
alter table public.split_bills enable row level security;
alter table public.split_bill_members enable row level security;
alter table public.split_bill_items enable row level security;
alter table public.split_bill_item_assignments enable row level security;
alter table public.subscriptions enable row level security;

create policy users_self on public.users for all to authenticated
  using (id = (select auth.uid())) with check (id = (select auth.uid()));

create policy categories_read on public.categories for select to authenticated
  using (user_id is null or user_id = (select auth.uid()));
create policy categories_insert on public.categories for insert to authenticated
  with check (user_id = (select auth.uid()));
create policy categories_update on public.categories for update to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
create policy categories_delete on public.categories for delete to authenticated
  using (user_id = (select auth.uid()));

create policy transactions_owner on public.transactions for all to authenticated
  using (user_id = (select auth.uid())) with check (
    user_id = (select auth.uid()) and exists (
      select 1 from public.categories c where c.id = category_id and (c.user_id is null or c.user_id = (select auth.uid()))
    )
  );
create policy budgets_owner on public.budgets for all to authenticated
  using (user_id = (select auth.uid())) with check (
    user_id = (select auth.uid()) and exists (
      select 1 from public.categories c where c.id = category_id and (c.user_id is null or c.user_id = (select auth.uid()))
    )
  );
create policy shopping_lists_owner on public.shopping_lists for all to authenticated
  using (user_id = (select auth.uid())) with check (
    user_id = (select auth.uid()) and exists (
      select 1 from public.categories c where c.id = category_id and (c.user_id is null or c.user_id = (select auth.uid()))
    )
  );
create policy shopping_items_owner on public.shopping_items for all to authenticated
  using (exists (select 1 from public.shopping_lists l where l.id = shopping_list_id and l.user_id = (select auth.uid())))
  with check (exists (select 1 from public.shopping_lists l where l.id = shopping_list_id and l.user_id = (select auth.uid())));

create policy split_bills_owner on public.split_bills for all to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
create policy split_members_owner on public.split_bill_members for all to authenticated
  using (exists (select 1 from public.split_bills b where b.id = split_bill_id and b.user_id = (select auth.uid())))
  with check (exists (select 1 from public.split_bills b where b.id = split_bill_id and b.user_id = (select auth.uid())));
create policy split_items_owner on public.split_bill_items for all to authenticated
  using (exists (select 1 from public.split_bills b where b.id = split_bill_id and b.user_id = (select auth.uid())))
  with check (exists (select 1 from public.split_bills b where b.id = split_bill_id and b.user_id = (select auth.uid())));
create policy split_assignments_owner on public.split_bill_item_assignments for all to authenticated
  using (exists (
    select 1 from public.split_bill_items i
    join public.split_bills b on b.id = i.split_bill_id
    join public.split_bill_members m on m.id = split_bill_member_id and m.split_bill_id = b.id
    where i.id = split_bill_item_id and b.user_id = (select auth.uid())
  ))
  with check (exists (
    select 1 from public.split_bill_items i
    join public.split_bills b on b.id = i.split_bill_id
    join public.split_bill_members m on m.id = split_bill_member_id and m.split_bill_id = b.id
    where i.id = split_bill_item_id and b.user_id = (select auth.uid())
  ));
create policy subscriptions_owner on public.subscriptions for all to authenticated
  using (user_id = (select auth.uid())) with check (
    user_id = (select auth.uid()) and exists (
      select 1 from public.categories c where c.id = category_id and (c.user_id is null or c.user_id = (select auth.uid()))
    )
  );

-- Guest Link RPC: read-only, exposes bill details without member phone numbers.
create or replace function public.get_guest_split_bill(p_guest_token uuid)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select jsonb_build_object(
    'id', b.id,
    'title', b.title,
    'total_amount', b.total_amount,
    'tax_amount', b.tax_amount,
    'discount_amount', b.discount_amount,
    'status', b.status,
    'created_at', b.created_at,
    'members', coalesce((
      select jsonb_agg(jsonb_build_object('name', m.name, 'amount_owed', m.amount_owed, 'is_paid', m.is_paid) order by m.id)
      from public.split_bill_members m where m.split_bill_id = b.id
    ), '[]'::jsonb),
    'items', coalesce((
      select jsonb_agg(jsonb_build_object('name', i.name, 'price', i.price, 'quantity', i.quantity) order by i.id)
      from public.split_bill_items i where i.split_bill_id = b.id
    ), '[]'::jsonb)
  )
  from public.split_bills b
  where b.guest_token = p_guest_token;
$$;
revoke all on function public.get_guest_split_bill(uuid) from public;
grant execute on function public.get_guest_split_bill(uuid) to anon, authenticated;
